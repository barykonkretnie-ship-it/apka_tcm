import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
const root = new URL('./', import.meta.url);
const data = JSON.parse(await readFile(new URL('content/patterns.json', root), 'utf8'));
const logic = await readFile(new URL('quiz-engine.js', root), 'utf8');
const dataset = `// Generated by npm run build from content/patterns.json.\nexport const patterns = ${JSON.stringify(data, null, 2)};\n${logic}`;
await writeFile(new URL('public/questions.js', root), dataset);
if (process.argv.includes('--web-only')) {
  console.log(`Zbudowano stronę statyczną: public/ (${data.length} wzorców).`);
  process.exit(0);
}
let html = await readFile(new URL('public/index.html', root), 'utf8');
const css = await readFile(new URL('public/style.css', root), 'utf8');
const app = await readFile(new URL('public/app.js', root), 'utf8');
html = html.replace('<link rel="stylesheet" href="/style.css">', `<style>${css}</style>`)
  .replace('<script type="module" src="/app.js"></script>', '')
  .replace('href="/" aria-label=', 'href="#" aria-label=')
  .replace('</body>', `<script>${dataset.replace(/^export /gm, '')}\n${app.replace(/^import .*;\n/gm, '')}</script></body>`);
for (const filename of ['korzenie.html', 'korzenie-poprawione.html', 'korzenie-kafelki.html', 'korzenie-baza.html']) {
  await writeFile(new URL('../' + filename, root), html);
}
console.log(`Zbudowano bazę ${data.length} wzorców oraz samodzielny plik ${fileURLToPath(new URL('../korzenie-baza.html', root))}`);
